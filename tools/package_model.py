"""Package a distilled encoder with a model card that carries its measured numbers.

`tools/finetune.py --teacher-models` produces a local model directory; this copies it to a
release directory and writes a `MODEL_CARD.md` stating what it is, how it was trained and
what it scored — including the zero-shot baseline and the teacher ensemble it was distilled
from, so the artefact cannot be read as zero-shot. The card is generated from the
`tools/distill_eval.py` report, so the numbers travel with the model instead of living only
in a findings document.

    .venv/bin/python tools/package_model.py --model eval/distill-nfcorpus-model \
        --report eval/distill-eval.json --out eval/distill-nfcorpus-package
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path
from typing import Any, Mapping, Sequence

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "src"))
import evalkit  # noqa: E402


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(prog="package_model.py")
    ap.add_argument("--model", default=str(ROOT / "eval" / "distill-nfcorpus-model"))
    ap.add_argument("--report", default=str(ROOT / "eval" / "distill-eval.json"))
    ap.add_argument("--out", default=str(ROOT / "eval" / "distill-nfcorpus-package"))
    ap.add_argument("--card-name", default="MODEL_CARD.md")
    return ap.parse_args(argv)


def render_card(report: Mapping[str, Any], *, model_id: str, pooling: str | None = None) -> str:
    """A model card from a ``distill_eval`` report: what it is and how it scored."""
    settings = report.get("_settings", {})
    summary = report.get("summary", {})
    comparisons = report.get("comparisons", {})
    dataset = settings.get("dataset", "unknown")

    def score(name: str) -> str:
        row = summary.get(name)
        return f"{row['nDCG@10']:.4f}" if row else "—"

    lines = [
        f"# {model_id}",
        "",
        "A **domain-adapted** bi-encoder distilled from a dense ensemble. It is **not** a",
        "zero-shot model: the numbers below are fine-tuned on a train split and scored on a",
        "held-out test split, and must never be compared as if they were zero-shot.",
        "",
        f"- dataset: `{dataset}`",
        f"- test queries: {report.get('queries', '?')}",
        f"- teachers: {', '.join(settings.get('teachers', '').split(',')) or 'n/a'}",
        f"- student: `{settings.get('student', 'n/a')}`",
        f"- declared pooling: `{pooling or 'unknown'}` (overridable with `EMBED_POOLING`)",
        "",
        "## Measured nDCG@10 (test split)",
        "",
        "| model | nDCG@10 |",
        "| --- | --- |",
        f"| zero-shot student | {score('zero_shot')} |",
        f"| **this model (adapted)** | **{score('adapted')}** |",
        f"| teacher ensemble | {score('teacher_ensemble')} |",
        "",
        "## Paired comparison vs the zero-shot student",
        "",
    ]
    for name, value in comparisons.items():
        boot = value.get("bootstrap", {})
        if not boot:
            continue
        lines.append(
            f"- {name}: {boot['delta']:+.4f} "
            f"[{boot['ci_low']:+.4f}, {boot['ci_high']:+.4f}] — "
            f"{'significant' if boot.get('significant') else 'not significant'}"
        )
    lines += [
        "",
        "## Use",
        "",
        "```sh",
        f"EMBED_MODEL={model_id} laya-rag query \"...\"",
        "```",
        "",
        "The engine resolves pooling from the model's own `1_Pooling/config.json`. Measure",
        "`EMBED_POOLING` on your own data before trusting the default: for this NFCorpus",
        "artefact the declared CLS scores 0.3506 while mean pooling scores 0.3606, so the",
        "explicit `EMBED_POOLING=mean` is the better serving setting here.",
        "",
        "Generated by `tools/package_model.py`; scores come from `tools/distill_eval.py`.",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    model_dir = Path(args.model)
    if not model_dir.is_dir():
        raise SystemExit(f"{model_dir} is not a directory; train one with tools/finetune.py")
    out = Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(model_dir, out)

    report_path = Path(args.report)
    if not report_path.is_file():
        raise SystemExit(f"{report_path} is missing; run tools/distill_eval.py first")
    report = json.loads(report_path.read_text(encoding="utf-8"))
    from laya_rag.model import saved_pooling

    card = render_card(report, model_id=out.name, pooling=saved_pooling(str(model_dir)))
    evalkit.write_text(out / args.card_name, card)
    print(card)
    print(f"packaged {model_dir} -> {out} ({len(card)} bytes of card)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
